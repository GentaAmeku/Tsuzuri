counter = {"n": 0}


def bid():
    counter["n"] += 1
    return f"b{counter['n']:02d}"


def text(t):
    return {"id": bid(), "type": "text", "props": {"text": t}}


def bullets(items):
    return {"id": bid(), "type": "bullets", "props": {"items": items}}


def ordered(items):
    return {
        "id": bid(),
        "type": "ordered",
        "props": {"items": [{"text": t, "why": w} if w else {"text": t} for t, w in items]},
    }


def table(headers, rows, row_label=False):
    props = {"headers": headers, "rows": rows}
    if row_label:
        props["rowLabel"] = True
    return {"id": bid(), "type": "table", "props": props}


def notice(kind, t, label=None):
    props = {"kind": kind, "text": t}
    if label:
        props["label"] = label
    return {"id": bid(), "type": "notice", "props": props}


def note(t):
    return {"id": bid(), "type": "note", "props": {"text": t}}


def open_(t):
    return {"id": bid(), "type": "open", "props": {"text": t}}


def code(t, lang, caption):
    return {"id": bid(), "type": "code", "props": {"text": t, "lang": lang, "caption": caption}}


def image(src, alt, caption):
    return {"id": bid(), "type": "image", "props": {"src": str(src), "alt": alt, "caption": caption}}


def figure(html, caption):
    return {"id": bid(), "type": "figure", "props": {"html": html, "caption": caption}}


sections = []


def section(heading, blocks, level=2):
    sections.append(
        {"id": f"s{len(sections) + 1:02d}", "heading": heading, "level": level, "blocks": blocks}
    )


