import AppKit
import ApplicationServices
import TsuzuriCore

/// クリップボードを借りて ⌘V で貼り、0.3秒後に元の中身へ戻す(設計書「貼り付けはクリップボードを借りて、すぐ戻す」)
enum Paster {
    enum Outcome {
        case pasted
        case clipboardOnly
        /// 止めたときと違うアプリが前に来ていたので、貼らずにクリップボードに残した
        case appChanged
    }

    /// クリップボード履歴のアプリに残さないための印(nspasteboard.org)
    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    /// パスワード管理のアプリが付ける印。時間がたつと自分で消すので、戻すと消えるはずの秘密を残してしまう
    static let concealedTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    ]
    static let restoreDelay = Duration.milliseconds(300)

    /// - Parameter target: 止めたときにいちばん前にあったアプリ。違うアプリが前に来ていたら貼らない(nil なら確かめない)
    static func paste(_ text: String, target: pid_t? = nil) async -> Outcome {
        let pasteboard = NSPasteboard.general
        let front = NSWorkspace.shared.frontmostApplication
        let appChanged = target.map { $0 != front?.processIdentifier } ?? false
        let decision = PasteDecision.decide(focus: appChanged ? nil : focusedElement(), appBundleID: front?.bundleIdentifier, appChanged: appChanged)
        guard decision == .paste else {
            pasteboard.clearContents()
            pasteboard.setString(text, forType: .string)
            return decision == .appChanged ? .appChanged : .clipboardOnly
        }
        let saved = snapshot(pasteboard)
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: transientType)
        pasteboard.writeObjects([item])
        let ours = pasteboard.changeCount
        sendCommandV()
        try? await Task.sleep(for: restoreDelay)
        // 戻す前に本人が別のものをコピーしていたら、戻さない
        if pasteboard.changeCount == ours {
            pasteboard.clearContents()
            if !saved.isEmpty {
                pasteboard.writeObjects(saved)
            }
        }
        return .pasted
    }

    /// 元の中身を、型ごとのデータで写し取る。戻すときも履歴のアプリに二重に残さないよう印を付ける。
    /// パスワードなど隠す印の付いた中身は写さない(戻さず、空のままにする)
    static func snapshot(_ pasteboard: NSPasteboard) -> [NSPasteboardItem] {
        let items = pasteboard.pasteboardItems ?? []
        guard !items.contains(where: { !concealedTypes.isDisjoint(with: $0.types) }) else { return [] }
        return items.map { original in
            let copy = NSPasteboardItem()
            for type in original.types {
                if let data = original.data(forType: type) {
                    copy.setData(data, forType: type)
                }
            }
            copy.setData(Data(), forType: transientType)
            return copy
        }
    }

    static func sendCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        // 送っている間に本人が押している修飾キーが混ざらないようにする
        source?.setLocalEventsFilterDuringSuppressionState(
            [.permitLocalMouseEvents, .permitSystemDefinedEvents],
            state: .eventSuppressionStateSuppressionInterval
        )
        let vKey: CGKeyCode = 9
        for keyDown in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: keyDown) else { continue }
            event.flags = .maskCommand
            event.setIntegerValueField(.eventSourceUserData, value: KeyMonitor.syntheticMarker)
            event.post(tap: .cghidEventTap)
        }
    }

    /// Return を送る(録音中に Return が押されたとき、貼り終えてから)。自分のキーとして数えない印を付ける
    static func sendReturn() {
        let source = CGEventSource(stateID: .combinedSessionState)
        source?.setLocalEventsFilterDuringSuppressionState(
            [.permitLocalMouseEvents, .permitSystemDefinedEvents],
            state: .eventSuppressionStateSuppressionInterval
        )
        let returnKey: CGKeyCode = 36
        for keyDown in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: returnKey, keyDown: keyDown) else { continue }
            event.flags = []
            event.setIntegerValueField(.eventSourceUserData, value: KeyMonitor.syntheticMarker)
            event.post(tap: .cghidEventTap)
        }
    }

    /// フォーカスのある要素をアクセシビリティ API で読む。読めなければ nil
    static func focusedElement() -> PasteDecision.Focus? {
        let system = AXUIElementCreateSystemWide()
        AXUIElementSetMessagingTimeout(system, 0.3)
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &value) == .success,
              let value, CFGetTypeID(value) == AXUIElementGetTypeID() else { return nil }
        let element = value as! AXUIElement
        var role: CFTypeRef?
        AXUIElementCopyAttributeValue(element, kAXRoleAttribute as CFString, &role)
        var settable = DarwinBoolean(false)
        AXUIElementIsAttributeSettable(element, kAXValueAttribute as CFString, &settable)
        var range: CFTypeRef?
        let hasRange = AXUIElementCopyAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, &range) == .success
        return PasteDecision.Focus(role: role as? String ?? "", acceptsText: settable.boolValue || hasRange)
    }
}
